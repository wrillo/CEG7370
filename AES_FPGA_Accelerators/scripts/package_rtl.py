"""Rebuild the four standalone RTL files from the pinned vendor sources.
Run from any directory. Vendor algorithms are unchanged; names/library paths
are isolated and a common transaction wrapper is appended.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'implementations'
OUT.mkdir(exist_ok=True)

def bundle(repo, names, prefix, suffix, wrapper):
    files = [ROOT / 'vendor' / repo / name for name in names]
    texts = [p.read_text(encoding='utf-8-sig') for p in files]
    pattern = r'\bentity\s+(\w+)\s+is' if suffix == 'vhd' else r'\bmodule\s+(\w+)\s*\('
    identifiers = [m for t in texts for m in re.findall(pattern, t, re.I)]
    if repo == 'yaaes':
        identifiers += ['aes_pkg']
        texts = [t.replace('library aes_lib;', 'library work;').replace('aes_lib.', 'work.') for t in texts]
    rename = re.compile(r'\b(' + '|'.join(identifiers) + r')\b')
    comment = '--' if suffix == 'vhd' else '//'
    result = f'{comment} Generated by scripts/package_rtl.py. See SOURCES.md and vendor licenses.\n'
    for p, t in zip(files, texts):
        result += f'\n{comment} SOURCE: {p.relative_to(ROOT).as_posix()}\n' + rename.sub(lambda m: prefix + m[0], t) + '\n'
    result += '\n' + wrapper
    (OUT / f'aes128_ecb_{prefix[:-1]}.{suffix}').write_text(result, encoding='utf-8')

PORTS = '''library ieee;
use ieee.std_logic_1164.all;
entity TOP is
  port (clk, rst, start : in std_logic;
        key, plaintext : in std_logic_vector(127 downto 0);
        ready, done : out std_logic;
        ciphertext : out std_logic_vector(127 downto 0));
end entity;
'''

had = PORTS.replace('TOP', 'aes128_ecb_hadipour') + '''
architecture wrapper of aes128_ecb_hadipour is
  type state_t is (idle, load_block, encrypt);
  signal state : state_t := idle;
  signal k, p, c : std_logic_vector(127 downto 0) := (others => '0');
  signal run_core, core_done : std_logic;
  function reverse_bytes(x : std_logic_vector(127 downto 0)) return std_logic_vector is
    variable y : std_logic_vector(127 downto 0);
  begin
    for i in 0 to 15 loop y(i*8+7 downto i*8) := x(127-i*8 downto 120-i*8); end loop;
    return y;
  end;
begin
  ready <= '1' when state = idle and rst = '0' else '0';
  run_core <= '1' when state = encrypt and rst = '0' else '0';
  core : entity work.hadipour_aes_enc
    port map(clk => clk, rst => run_core, key => k, plaintext => p, ciphertext => c, done => core_done);
  process(clk) begin
    if rising_edge(clk) then
      done <= '0';
      if rst = '1' then
        state <= idle; ciphertext <= (others => '0'); k <= (others => '0'); p <= (others => '0');
      else
        case state is
          when idle => if start = '1' then k <= reverse_bytes(key); p <= reverse_bytes(plaintext); state <= load_block; end if;
          when load_block => state <= encrypt;
          when encrypt => if core_done = '1' then ciphertext <= reverse_bytes(c); done <= '1'; state <= idle; end if;
        end case;
      end if;
    end if;
  end process;
end architecture;
'''
bundle('hadipour', ['AES-ENC/RTL/'+x+'.vhd' for x in ['reg','gfmult_by2','sbox','add_round_key','shift_rwos','sub_byte','column_calculator','mix_columns','key_sch_round_function','key_schedule','controller','aes_enc']], 'hadipour_', 'vhd', had)

# Use YAAES cipher directly: avoids the serial key/IV input converter and
# retains its published two-stage iterative round architecture.
yaa = PORTS.replace('TOP', 'aes128_ecb_yaaes') + '''
library ieee;
use ieee.numeric_std.all;
use work.yaaes_aes_pkg.all;
architecture wrapper of aes128_ecb_yaaes is
  signal busy : std_logic := '0';
  signal launch, valid : std_logic := '0';
  signal p, k : std_logic_vector(127 downto 0) := (others => '0');
  signal result_state : st_state;
  -- The upstream core has initialization but no reset. Drain it after reset.
  signal drain : integer range 0 to 32 := 32;
begin
  ready <= '1' when busy = '0' and drain = 0 and rst = '0' else '0';
  core : entity work.yaaes_cipher generic map(G_KEY_WORDS => 4)
    port map(isl_clk => clk, isl_valid => launch,
      ia_data => transpose(slv_to_state_array(p)), ia_key => slv_to_key_array(k),
      oa_data => result_state, osl_valid => valid);
  process(clk) begin
    if rising_edge(clk) then
      done <= '0'; launch <= '0';
      if rst = '1' then
        busy <= '0'; drain <= 32; ciphertext <= (others => '0');
      elsif drain /= 0 then drain <= drain - 1;
      elsif busy = '0' then
        if start = '1' then p <= plaintext; k <= key; launch <= '1'; busy <= '1'; end if;
      elsif valid = '1' then
        ciphertext <= array_to_slv(transpose(result_state)); done <= '1'; busy <= '0';
      end if;
    end if;
  end process;
end architecture;
'''
bundle('yaaes', ['src/'+x+'.vhd' for x in ['aes_pkg','key_expansion','cipher']], 'yaaes_', 'vhd', yaa)

for repo, prefix in [('secworks', 'secworks_'), ('secworks_cmt', 'cmt_')]:
    wrapper = '''
`default_nettype none
module TOP(input wire clk, rst, start,
  input wire [127:0] key, plaintext,
  output wire ready, output reg done, output reg [127:0] ciphertext);
  localparam IDLE=0, INIT=1, KEY_BUSY=2, KEY_WAIT=3, NEXT=4, DATA_BUSY=5, DATA_WAIT=6;
  reg [2:0] state = IDLE;
  reg [127:0] k, p;
  wire core_ready, core_valid;
  wire [127:0] result;
  assign ready = (state == IDLE) && !rst;
  CORE core(.clk(clk), .reset_n(!rst), .encdec(1'b1),
    .init(state == INIT), .next(state == NEXT), .ready(core_ready),
    .key({k,128'b0}), .keylen(1'b0), .block(p), .result(result), .result_valid(core_valid));
  always @(posedge clk) begin
    done <= 1'b0;
    if (rst) begin state <= IDLE; k <= 0; p <= 0; ciphertext <= 0; end
    else case (state)
      IDLE: if (start) begin k <= key; p <= plaintext; state <= INIT; end
      INIT: state <= KEY_BUSY;
      KEY_BUSY: if (!core_ready) state <= KEY_WAIT;
      KEY_WAIT: if (core_ready) state <= NEXT;
      NEXT: state <= DATA_BUSY;
      DATA_BUSY: if (!core_ready) state <= DATA_WAIT;
      DATA_WAIT: if (core_ready && core_valid) begin ciphertext <= result; done <= 1'b1; state <= IDLE; end
      default: state <= IDLE;
    endcase
  end
endmodule
`default_nettype wire
'''.replace('TOP', 'aes128_ecb_'+prefix[:-1]).replace('CORE', prefix+'aes_core')
    bundle(repo, ['src/rtl/'+x+'.v' for x in ['aes_sbox','aes_inv_sbox','aes_key_mem','aes_encipher_block','aes_decipher_block','aes_core']], prefix, 'v', wrapper)

